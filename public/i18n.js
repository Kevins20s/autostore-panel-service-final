function gsT(value, ...args) {
    const source = Array.isArray(value)
        ? value.map((part, index) => index ? "{" + (index - 1) + "}" + part : part).join("")
        : value;
    const key = source.trim();
    const english = gsLanguage === "en" && Object.hasOwn(gsEnglish, key) ? gsEnglish[key] : key;
    const text = source.replace(/\S(?:[\s\S]*\S)?/, () => english);
    return args.length ? text.replace(/\{(\d+)\}/g, (token, index) => index < args.length ? String(args[index]) : token) : text;
}

document.documentElement.lang = gsLanguage;
if (gsLanguage === "en") {
    const textNodes = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
        acceptNode: node => node.parentElement.closest("script, style") ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT
    });
    while (textNodes.nextNode()) textNodes.currentNode.nodeValue = gsT(textNodes.currentNode.nodeValue);
    for (const attr of ["aria-label", "placeholder", "title", "alt"]) {
        for (const el of document.querySelectorAll("[" + attr + "]")) el.setAttribute(attr, gsT(el.getAttribute(attr)));
    }
    document.title = gsT(document.title);
}

const gsLanguageSelect = document.createElement("select");
gsLanguageSelect.className = "language-select";
gsLanguageSelect.id = "languageSelect";
gsLanguageSelect.setAttribute("aria-label", gsLanguage === "en" ? "Language" : "Bahasa");
gsLanguageSelect.append(new Option("ID", "id"), new Option("EN", "en"));
gsLanguageSelect.value = gsLanguage;
gsLanguageSelect.addEventListener("change", () => {
    const language = gsLanguageSelect.value;
    const url = new URL(location.href);
    try {
        localStorage.setItem("gs-language", language);
        url.searchParams.delete("lang");
    } catch {
        url.searchParams.set("lang", language);
    }
    if (url.href === location.href) location.reload();
    else location.replace(url.href);
});
document.body.append(gsLanguageSelect);
